import assert from 'node:assert/strict';
import test from 'node:test';
import { mkdtemp, writeFile, rm, mkdir, symlink } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { inspectSystemDns, boundedInspectRead, DNS_INSPECT_FILES, DNS_INSPECT_UNITS } from './lib/dns-inspect.mjs';
import { runCommand } from './lib/transparent-acceptance.mjs';

function fixture(overrides = {}) {
  const data = { resolver: 'nameserver 10.23.45.67\nsearch secret.corp\n', nss: 'hosts: files dns\n',
    init: 'systemd\n', mounts: '1 2 0:1 / / rw - ext4 /dev/private rw\n', ...overrides };
  return { read: async (path) => data[Object.keys(DNS_INSPECT_FILES).find((key) => DNS_INSPECT_FILES[key] === path)],
    metadata: async () => ({ kind: 'regular', target: '/etc/resolv.conf' }), probe: async () => 'inactive' };
}
test('regular resolv.conf and inactive units never authorize unmanaged backend', async () => {
  const r = await inspectSystemDns(fixture()); assert.equal(r.backend, 'unselected');
  assert.deepEqual(r.assessment.candidates, []); assert.equal(r.assessment.requiresReview, true);
  assert.ok(r.assessment.reasons.includes('no-manager-evidence-is-not-proof-of-unmanaged-DNS'));
});
for (const [path, candidate] of [['/run/systemd/resolve/stub-resolv.conf', 'systemd-resolved'],
  ['/run/systemd/resolve/resolv.conf', 'systemd-resolved'], ['/run/NetworkManager/resolv.conf', 'NetworkManager'],
  ['/run/resolvconf/resolv.conf', 'resolvconf']]) test(`known symlink evidence: ${candidate}/${path}`, async () => {
  const f = fixture(); f.metadata = async () => ({ kind: 'symlink', target: path });
  const r = await inspectSystemDns(f); assert.deepEqual(r.assessment.candidates, [candidate]);
  assert.equal(r.backend, 'unselected'); assert.equal(r.resolver.object, 'symlink');
});
test('NM and resolved may coexist, not an automatic conflict or backend choice', async () => {
  const f = fixture({ resolver: '# Generated by NetworkManager\nnameserver 127.0.0.53\n' });
  f.probe = async (unit) => unit === 'NetworkManager.service' ? 'active' : 'inactive';
  const r = await inspectSystemDns(f); assert.deepEqual(r.assessment.candidates, ['systemd-resolved', 'NetworkManager']);
  assert.ok(r.assessment.reasons.includes('multiple-components-may-form-a-manager-to-resolver-chain'));
});
test('NSS resolve detected without leaking custom service or action syntax', async () => {
  const r = await inspectSystemDns(fixture({ nss: 'hosts: files resolve [!UNAVAIL=return] secretplugin dns # private\n' }));
  assert.deepEqual(r.nss.services, ['files', 'resolve', 'other', 'dns']); assert.equal(r.nss.customService, true);
  assert.ok(r.assessment.candidates.includes('systemd-resolved')); assert.ok(!JSON.stringify(r).includes('secretplugin'));
});
test('no system bus probe when PID1 is not systemd even if runtime dirs exist', async () => {
  const f = fixture({ init: 'private-workspace-process\n' }); f.probe = async () => { assert.fail('must not contact host bus'); };
  const r = await inspectSystemDns(f); assert.equal(r.environment.pid1, 'other');
  assert.ok(Object.values(r.units).every((state) => state === 'not-probed'));
});
test('denied reads and probes are unknown, not absence', async () => {
  const f = fixture(); f.read = async () => { throw new Error('secret EACCES'); };
  f.metadata = async () => { throw new Error('secret path'); };
  const r = await inspectSystemDns(f); assert.equal(r.resolver.status, 'unavailable');
  assert.equal(r.resolver.mountpoint, null); assert.equal(r.environment.pid1, 'unknown');
  assert.ok(!JSON.stringify(r).includes('secret'));
  const denied = fixture(); denied.probe = async () => { throw new Error('permission'); };
  assert.ok(Object.values((await inspectSystemDns(denied)).units).every((value) => value === 'unknown'));
});
test('mountpoint is detected without exposing source paths or device ids', async () => {
  const r = await inspectSystemDns(fixture({ mounts: '123 456 0:789 /private/secret /etc/resolv.conf rw - ext4 /dev/secret rw\n' }));
  assert.equal(r.resolver.mountpoint, true); assert.ok(!JSON.stringify(r).includes('secret'));
});
test('IP addresses, search domains, paths and raw comments omitted', async () => {
  const f = fixture({ resolver: '# private-label\nnameserver 10.23.45.67\nnameserver 2001:db8::5\nnameserver ::1\nnameserver bad-secret\nsearch secret.corp\n' });
  f.metadata = async () => ({ kind: 'symlink', target: '/private/secret.conf' });
  const r = await inspectSystemDns(f), text = JSON.stringify(r);
  for (const secret of ['10.23.45.67', '2001:db8::5', '::1', 'bad-secret', 'secret.corp', '/private/', 'private-label']) assert.ok(!text.includes(secret));
  assert.deepEqual(r.resolver.nameservers, { ipv4: 1, ipv6: 2, loopback: 1, invalid: 1 });
  assert.equal(r.resolver.searchConfigured, true); assert.equal(r.dnsQueriesSent, 0); assert.equal(r.systemDnsChanged, false);
});
test('collector reads only fixed files and probes only fixed units', async () => {
  const f = fixture(), reads = [], probes = [], originalRead = f.read;
  f.read = async (path, limit) => { reads.push(path); assert.ok(limit <= 1048576); return originalRead(path); };
  f.probe = async (unit) => { probes.push(unit); return 'inactive'; };
  await inspectSystemDns(f);
  assert.deepEqual(reads.sort(), Object.values(DNS_INSPECT_FILES).sort()); assert.deepEqual(probes.sort(), [...DNS_INSPECT_UNITS].sort());
});
test('bounded reader accepts exact limit and rejects oversize/directories', async (t) => {
  const dir = await mkdtemp(join(tmpdir(), 'meshpn-inspect-')); t.after(() => rm(dir, { recursive: true, force: true }));
  const file = join(dir, 'file'); await writeFile(file, '1234');
  assert.equal(await boundedInspectRead(file, 4), '1234'); await assert.rejects(boundedInspectRead(file, 3));
  await mkdir(join(dir, 'directory')); await assert.rejects(boundedInspectRead(join(dir, 'directory')));
  await symlink(file, join(dir, 'link')); assert.equal(await boundedInspectRead(join(dir, 'link'), 4), '1234');
});
test('CLI accepts only help or no options, never --apply/remote/arbitrary paths', async () => {
  for (const arg of ['--apply', '--host=remote', '--file=/etc/shadow', '--help=1']) {
    const r = await runCommand(process.execPath, ['scripts/dns-inspect.mjs', arg]);
    assert.equal(r.code, 1); assert.equal(r.stdout, '');
  }
  const help = await runCommand(process.execPath, ['scripts/dns-inspect.mjs', '--help']);
  assert.equal(help.code, 0); assert.match(help.stdout, /Read-only/);
});
